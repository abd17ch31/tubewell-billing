const assert = require("node:assert/strict");
const fs = require("node:fs");
const test = require("node:test");
const {
  createDatabase,
  getConnectionOptions,
  toPostgresSql,
} = require("../server/db");

function createFakePool() {
  const calls = [];
  const client = {
    async query(sql, values) {
      calls.push({ sql, values });
      if (sql === "INSERT INTO customers (name) VALUES ($1) RETURNING id") {
        return { rows: [{ id: 7 }], rowCount: 1 };
      }
      if (sql.startsWith("SELECT")) return { rows: [{ id: 7 }], rowCount: 1 };
      return { rows: [], rowCount: 1 };
    },
    release() { calls.push("release"); },
  };
  return {
    calls,
    async query(sql, values) {
      calls.push({ sql, values });
      if (sql === "INSERT INTO customers (name) VALUES ($1) RETURNING id") {
        return { rows: [{ id: 7 }], rowCount: 1 };
      }
      if (sql.startsWith("SELECT")) return { rows: [{ id: 7 }], rowCount: 1 };
      return { rows: [], rowCount: 1 };
    },
    async connect() { return client; },
    async end() { calls.push("end"); },
  };
}

test("Supabase database URL validates connection URL and scheme", () => {
  assert.throws(() => getConnectionOptions({}), /SUPABASE_DB_URL/);
  assert.throws(() => getConnectionOptions({ SUPABASE_DB_URL: "https://example.com/db" }), /postgres/);
  assert.throws(() => getConnectionOptions({ SUPABASE_DB_URL: "postgresql://localhost" }), /database name/);

  const options = getConnectionOptions({
    SUPABASE_DB_URL: "postgresql://postgres:secret@db.example.supabase.co:5432/postgres",
  });
  assert.match(options.connectionString, /^postgresql:/);
  assert.deepEqual(options.ssl, { rejectUnauthorized: true });

  const withCa = getConnectionOptions({
    SUPABASE_DB_URL: "postgresql://postgres:secret@db.example.supabase.co:5432/postgres",
    SUPABASE_DB_SSL_CA: __filename,
  });
  assert.equal(withCa.ssl.ca, fs.readFileSync(__filename, "utf8"));
  assert.throws(() => getConnectionOptions({
    SUPABASE_DB_URL: "postgresql://postgres:secret@db.example.supabase.co:5432/postgres",
    SUPABASE_DB_SSL_CA: "./missing-supabase-root.crt",
  }), /Could not read Supabase root certificate/);
});

test("query adapter converts placeholders and quoted identifiers for PostgreSQL", () => {
  assert.equal(
    toPostgresSql('SELECT `key` FROM settings WHERE id = ? AND name = ?'),
    'SELECT "key" FROM settings WHERE id = $1 AND name = $2',
  );
});

test("database adapter returns rows and PostgreSQL RETURNING metadata", async () => {
  const pool = createFakePool();
  const db = createDatabase(pool);

  assert.deepEqual(await db.query("SELECT id FROM customers WHERE id = ?", [7]), [{ id: 7 }]);
  const result = await db.execute("INSERT INTO customers (name) VALUES (?) RETURNING id", ["A"]);
  assert.equal(result.insertId, 7);
  assert.equal(result.affectedRows, 1);
  assert.deepEqual(pool.calls.slice(0, 2).map((call) => call.values), [[7], ["A"]]);
});

test("database transactions commit and release on success and rollback on failure", async () => {
  const pool = createFakePool();
  const db = createDatabase(pool);

  assert.equal(await db.transaction(async (tx) => {
    const result = await tx.execute("INSERT INTO customers (name) VALUES (?) RETURNING id", ["A"]);
    return result.insertId;
  }), 7);
  assert.deepEqual(pool.calls.filter((call) => typeof call === "object").map((call) => call.sql), [
    "BEGIN",
    "INSERT INTO customers (name) VALUES ($1) RETURNING id",
    "COMMIT",
  ]);
  assert.equal(pool.calls.at(-1), "release");

  const failure = new Error("allocation failed");
  await assert.rejects(db.transaction(async () => { throw failure; }), failure);
  assert.deepEqual(pool.calls.filter((call) => typeof call === "object").slice(-2).map((call) => call.sql), [
    "BEGIN",
    "ROLLBACK",
  ]);
  assert.equal(pool.calls.at(-1), "release");
});

test("database initialization executes PostgreSQL schema and seeds defaults idempotently", async () => {
  const pool = createFakePool();
  const db = createDatabase(pool);

  await db.initialize();
  const sql = pool.calls.filter((call) => typeof call === "object").map((call) => call.sql);
  assert.ok(sql.some((statement) => statement.includes("GENERATED BY DEFAULT AS IDENTITY")));
  assert.ok(sql.some((statement) => statement.includes("REFERENCES customers")));
  const seed = sql.filter((statement) => statement.includes('ON CONFLICT ("key") DO NOTHING'));
  assert.equal(seed.length, 4);
});
